"""Write docs/settings.md from qcopt's options models (``--check``: fail if it differs).

The models are the one source of every setting's name, type, default, unit, tier and
meaning; this script renders them, and a test keeps the page current.
"""

from __future__ import annotations

import inspect
import re
import sys
import types
import typing
from pathlib import Path
from typing import Any

from pydantic import BaseModel

from qcopt.options import OPTIONS, _Settings

DOC = Path(__file__).resolve().parents[1] / "docs" / "settings.md"
TITLES = {
    "optimization": 'Minimization (`calctype="optimization"`)',
    "transition_state": 'Transition-state search (`calctype="transition_state"`)',
    "irc": 'IRC (`calctype="irc"`)',
}


def _attributes(cls: type) -> tuple[str, dict[str, str]]:
    """The docstring's summary paragraph and its ``Attributes:`` entries."""
    doc = inspect.cleandoc(cls.__doc__ or "")
    head, _, rest = doc.partition("\nAttributes:\n")
    summary = " ".join(head.strip().split("\n\n")[0].split())
    attrs: dict[str, str] = {}
    name = None
    for line in rest.splitlines():
        m = re.match(r"    (\w+): (.*)", line)
        if m:
            name = m.group(1)
            attrs[name] = m.group(2).strip()
        elif name and line.startswith("        "):
            attrs[name] += " " + line.strip()
    for base in cls.__mro__[1:]:
        if issubclass(base, _Settings) and base is not _Settings:
            attrs = {**_attributes(base)[1], **attrs}
    return summary, attrs


def _default(value: Any) -> str:
    if value is None:
        return "off"
    if isinstance(value, float):
        return f"{value:.6g}"
    if isinstance(value, list):
        return "[]" if not value else repr(value)
    return f"`{value}`" if isinstance(value, str) else str(value)


def _type(ann: Any) -> str:
    """A readable type: enums as their values, lists, optional values."""
    origin, args = typing.get_origin(ann), typing.get_args(ann)
    if origin is typing.Literal:
        return ", ".join(f"`{a}`" for a in args)
    if origin in (typing.Union, types.UnionType):
        kinds = [_type(a) for a in args if a is not type(None)]
        return " or ".join(kinds) + (" or None" if type(None) in args else "")
    if origin is list:
        return f"list of {_type(args[0])}"
    return getattr(ann, "__name__", str(ann))


def _md(text: str) -> str:
    """Docstring markup (reStructuredText roles, double backticks) as Markdown."""
    text = re.sub(r":\w+:`~?([\w.]+)`", r"`\1`", text)
    return text.replace("``", "`").replace("|", "\\|")


def _rows(model: type[BaseModel], attrs: dict[str, str], prefix: str = "") -> list[str]:
    rows = []
    for key, field in model.model_fields.items():
        extra = (
            field.json_schema_extra if isinstance(field.json_schema_extra, dict) else {}
        )
        unit = extra.get("unit", "")
        tier = extra.get("tier", "")
        meaning = _md(attrs.get(key, ""))
        rows.append(
            f"| `{prefix}{key}` | {_type(field.annotation)} | {_default(field.default)} | {unit} "
            f"| {tier} | {meaning} |"
        )
    return rows


def render() -> str:
    """The settings reference as Markdown."""
    out = [
        "# Settings",
        "",
        "Generated by `scripts/settings_doc.py` from `qcopt.options`; do not edit by hand.",
        "",
        "Settings are `group.key` (a dict per group) or top-level scalars. Atomic units "
        "(bohr, Hartree) unless the unit column says otherwise. *Tier*: `common` settings "
        "are the ones most runs change; `expert` ones rarely need changing. "
        "`qcopt.default_options(calctype)` returns the same defaults, "
        "`qcopt.options_schema(calctype)` the JSON Schema.",
        "",
    ]
    for calctype, model in OPTIONS.items():
        summary, top = _attributes(model)
        out += [f"## {TITLES[calctype]}", "", _md(summary), ""]
        scalars = {
            k: f
            for k, f in model.model_fields.items()
            if not (
                isinstance(f.annotation, type) and issubclass(f.annotation, _Settings)
            )
        }
        if scalars:
            out += [
                "| setting | type | default | unit | tier | meaning |",
                "|---|---|---|---|---|---|",
            ]
            sub = type("Top", (BaseModel,), {"__annotations__": {}})
            sub.model_fields = scalars  # type: ignore[misc]
            out += _rows(sub, top)
            out.append("")
        for name, field in model.model_fields.items():
            group = field.annotation
            if not (isinstance(group, type) and issubclass(group, _Settings)):
                continue
            gsummary, attrs = _attributes(group)
            out += [f"### `{name}`", "", _md(gsummary), ""]
            out += [
                "| setting | type | default | unit | tier | meaning |",
                "|---|---|---|---|---|---|",
            ]
            out += _rows(group, attrs, f"{name}.")
            out.append("")
    return "\n".join(out).rstrip() + "\n"


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if DOC.read_text() == text else 1)
    DOC.write_text(text)
    print(f"wrote {DOC}")
